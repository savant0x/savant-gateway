import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import test from "node:test";

import {
  findAttributionHits,
  maskCode,
} from "../scripts/attribution-patterns.mjs";
import { scanDocuments } from "../scripts/attribution-document-guard.mjs";

test("credit lines are detected and ordinary vendor prose is not", () => {
  const hits = findAttributionHits(
    [
      "Generated with Codebuff",
      "Co-Authored-By: Claude <noreply@example.com>",
      "Anthropic published a model today.",
      "Generated with the OpenAI SDK is a legitimate technical statement.",
      "Written by Claude Shannon in 1948.",
      "🤖 is an emoji, not a credit line.",
    ].join("\n"),
  );

  assert.deepEqual(
    hits.map((hit) => hit.line),
    [1, 2],
  );
});

test("fenced and inline code do not become attribution findings", () => {
  const text = [
    "```text",
    "Generated with Codebuff",
    "```",
    "Use `Co-Authored-By: Codebuff` as an example only.",
    "Actual credit follows:",
    "Generated by Codebuff",
  ].join("\n");
  const hits = findAttributionHits(text);

  assert.equal(maskCode(text).includes("Generated by Codebuff"), true);
  assert.deepEqual(
    hits.map((hit) => hit.line),
    [6],
  );
});

test("robot emoji needs a credit cue", () => {
  assert.equal(findAttributionHits("Generated with 🤖").length, 1);
  assert.equal(findAttributionHits("The robot emoji 🤖 is decorative.").length, 0);
});

test("governed documents are scanned and research copies are excluded", () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "attribution-docs-"));

  try {
    fs.mkdirSync(path.join(root, "docs", "research"), { recursive: true });
    fs.mkdirSync(path.join(root, "dev", "fids"), { recursive: true });
    fs.writeFileSync(path.join(root, "README.md"), "Generated with Codebuff\n");
    fs.writeFileSync(
      path.join(root, "dev", "fids", "test.md"),
      "Co-Authored-By: Claude <noreply@example.com>\n",
    );
    fs.writeFileSync(
      path.join(root, "docs", "research", "quoted.md"),
      "Generated with Codebuff\n",
    );

    const hits = scanDocuments(root);

    assert.deepEqual(
      hits.map((hit) => `${hit.file}:${hit.line}`),
      ["README.md:1", "dev/fids/test.md:1"],
    );
  } finally {
    fs.rmSync(root, { recursive: true, force: true });
  }
});

test("the message-file CLI fails closed on a credit line", () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "attribution-cli-"));
  const message = path.join(root, "message.txt");

  try {
    fs.writeFileSync(message, "feat: test\n\nGenerated with Codebuff\n");

    assert.throws(
      () =>
        execFileSync(
          process.execPath,
          ["scripts/attribution-guard.mjs", "--message-file", message],
          { cwd: process.cwd(), stdio: "pipe" },
        ),
      (error) => error.status === 1,
    );

    fs.writeFileSync(message, "feat: test\n\nNo agent credit.\n");

    const output = execFileSync(
      process.execPath,
      ["scripts/attribution-guard.mjs", "--message-file", message],
      { cwd: process.cwd(), encoding: "utf8" },
    );

    assert.match(output, /PASS/);
  } finally {
    fs.rmSync(root, { recursive: true, force: true });
  }
});
